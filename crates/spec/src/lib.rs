/// doc の `ja:` と `en:` の行に書いた文。
#[derive(Default)]
struct Text {
    ja: Option<String>,
    en: Option<String>,
}

/// doc の行から `ja:` と `en:` の文を読む。`at` はエラーに出す場所。
///
/// 同じ印の行が 2 つあるとき、印の行の次の行が空行でも印の行でもないときはエラーにする。
/// 後者は、文を 2 行に分けて書いたときに 2 行目を読み落とさないため。
fn text(lines: &[String], at: &str) -> Result<Text, String> {
    let (text, _) = lines
        .iter()
        .try_fold((Text::default(), false), |(text, after), line| {
            let line = line.trim();
            match (line.strip_prefix("ja:"), line.strip_prefix("en:")) {
                (Some(ja), _) => match text.ja {
                    Some(_) => Err(format!("ja: が 2 つある: {at}")),
                    None => Ok((
                        Text {
                            ja: Some(ja.trim().to_string()),
                            ..text
                        },
                        true,
                    )),
                },
                (_, Some(en)) => match text.en {
                    Some(_) => Err(format!("en: が 2 つある: {at}")),
                    None => Ok((
                        Text {
                            en: Some(en.trim().to_string()),
                            ..text
                        },
                        true,
                    )),
                },
                _ if after && !line.is_empty() => {
                    Err(format!("ja: か en: の次の行に続きがある: {at}"))
                }
                _ => Ok((text, false)),
            }
        })?;
    Ok(text)
}

/// doc の `ja:` と `en:` の文。どちらかが無いか空なら、en に ASCII でない文字があれば、
/// どちらかに `\` かタブのような制御文字があれば、エラーにする。
fn both(lines: &[String], at: &str) -> Result<Both, String> {
    let Text { ja, en } = text(lines, at)?;
    match (ja.filter(|s| !s.is_empty()), en.filter(|s| !s.is_empty())) {
        (None, _) => Err(format!("doc に ja: の文が無い: {at}")),
        (Some(_), None) => Err(format!("doc に en: の文が無い: {at}")),
        (Some(_), Some(en)) if !en.is_ascii() => {
            Err(format!("en: の文に ASCII でない文字がある: {at}"))
        }
        (Some(ja), Some(en)) if ja.contains('\\') || en.contains('\\') => {
            Err(format!("ja: か en: の文に \\ がある: {at}"))
        }
        (Some(ja), Some(en)) if ja.chars().chain(en.chars()).any(char::is_control) => {
            Err(format!("ja: か en: の文に制御文字がある: {at}"))
        }
        (Some(ja), Some(en)) => Ok(Both { ja, en }),
    }
}

