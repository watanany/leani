//! テストとユーザーストーリーから、日本語の `SPEC.ja.md` と英語の `SPEC.en.md` を生成する。
//! 手で書いた一覧は必ずコードより古くなるので、手で書き足す場所は作らない。
//!
//! ```text
//! stories.toml                誰の何を助けるか。コードからは分からないので、ここが情報源
//! crates/leani/tests/*.rs     それを確かめているテスト。doc の ja: と en: の行が仕様の文になる
//! tests/test_*.py             Jupyter のカーネルのテスト (Python 版)
//! ```
//!
//! ```text
//! cargo run -p spec              # SPEC.ja.md と SPEC.en.md を書き直す
//! cargo run -p spec -- --check   # どちらかが生成結果と違えば 1 を返す
//! ```
//!
//! 各テストは `#[story(...)]` (カーネルのテストでは `@story(...)`) で、対象にするストーリーを
//! 指定する。対応は多対多でよい。テストの分け方はテストの都合 (失敗する理由が 1 つになるように、
//! なるべく速い層でテストするように) で決め、ストーリーは、テストが足りているかを数える表として
//! 使う。テストが 0 件のストーリーには「確かめているテストが無い。」と表示し、`unbuilt` にある
//! ストーリーには「まだ作っていない。」と表示する。
//!
//! Rust では、`#[test]` か `#[proptest]` の付いた関数をテストと見なし、テストを含む `mod` を
//! describe と見なす。テストの文は関数の doc comment (`///`) の `ja:` と `en:` の行から読み、
//! describe の文は `mod` の中の doc comment (`//!`) の `ja:` と `en:` の行から読む。
//!
//! Python のテストは行単位で読む。`def describe_` の行をインデントで入れ子にし、その中で
//! `@story(...)` の行 (1 行で書く) の次にある `def` をテストと見なす。describe とテストの文は、`def` の
//! すぐ後ろの docstring の `ja:` と `en:` の行から読む。Python の構文を解析する crate は使わない。
//! カーネルのテストは数が少なく、書き方も決まっているので、行単位で足りる。
//!
//! SPEC に載るのに実行されないことがあるテストと、実行されるのに SPEC に載らないテストは、
//! エラーにする。Rust では、`#[ignore]`、`#[cfg]`、`#[cfg_attr]` の付いたテストと `mod`、
//! 先頭に `#![cfg]` のあるファイル。Python では、skip と xfail のマーカー、`pytestmark`、
//! `if` や `for` や `with` の下の describe とテスト、`del` で消すか別の値を入れた `def` の名前。
//! どちらでも、`crates/leani/tests/` と `tests/` のサブディレクトリに置いたテストのファイル。
//! テストの中で `pytest.skip()` を呼んだときは、`tests/stories.py` が実行の結果で見つける。
//!
//! テストの関数名と `mod` の名前は、en の文から作る ([`ident`])。名前が違えばエラーにする。
//! 名前を別に考えなくてよいように、名前は文から機械的に決める。
//!
//! 文は `ja:` と `en:` の後ろに 1 行で書く。`ja:` か `en:` の次の行に続きを書くと、続きを
//! 読み落とすのでエラーにする。doc のほかの行には、テストの説明を自由に書いてよい。
//!
//! en の文は ASCII だけで書く。ja と en のどちらにも `\` を書かない。Python の docstring では
//! `\` がエスケープになり、Rust と Python で同じ文を書くテストがあるため。en が ja の訳として
//! 合っているかは確かめない。

