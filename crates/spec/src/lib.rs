/// テスト 1 件。`name` は関数名、`what` は doc の `ja:` と `en:` の文、`place` は「層 / describe」。
pub struct Test {
    pub name: String,
    pub what: Both,
    pub place: Both,
    pub stories: Vec<String>,
}

/// `#[story(...)]` に書かれたストーリー番号。付いていなければ空。番号を文字列で書いて
/// いなければエラーにする。`story` のマクロは何でも受け付けるので、コンパイルは通る。
fn marked(attrs: &[Attribute], at: &str) -> Result<Vec<String>, String> {
    attrs
        .iter()
        .filter(|a| a.path().segments.last().is_some_and(|s| s.ident == "story"))
        .map(|a| {
            a.parse_args_with(Punctuated::<LitStr, Token![,]>::parse_terminated)
                .map(|ids| ids.iter().map(LitStr::value).collect::<Vec<_>>())
                .map_err(|_| format!("#[story(...)] の番号は \"A1\" のように文字列で書く: {at}"))
        })
        .collect::<Result<Vec<_>, _>>()
        .map(|v| v.concat())
}

/// `#[test]` か `#[proptest]` が付いているか。テストはこの 2 つの属性で見分ける。
fn is_test(attrs: &[Attribute]) -> bool {
    attrs.iter().any(|a| {
        a.path()
            .segments
            .last()
            .is_some_and(|s| s.ident == "test" || s.ident == "proptest")
    })
}

/// `#[ignore]`、`cfg(test)` 以外の `#[cfg]`、`#[cfg_attr]` のどれかが付いているか。
/// どのテストも、`cargo nextest run` で実行されないことがある。`#[cfg_attr]` は中身を
/// 読まずにすべて含める。`#[cfg_attr(unix, ignore)]` のように、条件によって `ignore` か
/// `cfg` になるため。`#[core::prelude::v1::ignore]` のようなパスでも、最後の名前で判定する。
fn skipped(attrs: &[Attribute]) -> bool {
    attrs.iter().any(|a| {
        let last = a.path().segments.last().map(|s| s.ident.to_string());
        match last.as_deref() {
            Some("ignore" | "cfg_attr") => true,
            Some("cfg") => a
                .meta
                .require_list()
                .map_or(true, |l| l.tokens.to_string() != "test"),
            _ => false,
        }
    })
}

/// `mod x;` の中身。`dir` にある `x.rs` か `x/mod.rs` を読む。
fn mod_file(dir: &Path, name: &str) -> Result<syn::File, String> {
    let path = [
        dir.join(format!("{name}.rs")),
        dir.join(name).join("mod.rs"),
    ]
    .into_iter()
    .find(|p| p.is_file())
    .ok_or_else(|| format!("mod {name}; のファイルが無い: {}", dir.display()))?;
    let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    syn::parse_file(&text).map_err(|e| format!("{}: {e}", path.display()))
}

/// 外側の describe の文と内側の場所を ` / ` でつなぐ。内側が空なら外側だけ。
fn nest(outer: &str, inner: &str) -> String {
    match inner {
        "" => outer.to_string(),
        _ => format!("{outer} / {inner}"),
    }
}

/// Rust のテストファイル 1 つのテスト。場所は「層 / describe」で、`mod` の外のテストは
/// 層の名前だけにする。`dir` は、`mod x;` と書いたときに `x` のファイルを探すディレクトリ。
fn rust_tests(items: &[Item], layer: &str, dir: &Path) -> Result<Vec<Test>, String> {
    Ok(descend(items, layer, dir)?
        .into_iter()
        .map(|t| Test {
            place: t.place.map(|p| nest(layer, p)),
            ..t
        })
        .collect())
}

/// テストのファイル 1 つのテスト。ファイルの先頭に `#![cfg]` か `#![ignore]` があり、
/// テストを含むならエラーにする。
fn rust_file(file: &syn::File, layer: &str, dir: &Path) -> Result<Vec<Test>, String> {
    let tests = rust_tests(&file.items, layer, dir)?;
    match skipped(&file.attrs) && !tests.is_empty() {
        true => Err(format!("実行されないことがあるテスト: {layer}")),
        false => Ok(tests),
    }
}

/// `mod` を再帰的にたどってテストを集める。テストを含む `mod` が describe になる。
/// `mod` は入れ子にでき、返すテストの場所は、`items` の中の describe の文を ` / ` で
/// つないだもの。`at` は、エラーに出すための `mod` の名前の並び。
///
/// 次の書き方はエラーにする。どれも、SPEC と実行されるテストがずれるのに気づけない。
///
/// ```text
/// #[story] が付いているのにテストの属性が無い関数   実行されないのに載る
/// #[ignore]、#[cfg]、#[cfg_attr] が付いたテストと mod  実行されないことがあるのに載る
/// 直下のマクロ (proptest! など)                   中のテストを読めないので載らない
/// #[path] の付いた mod                            ファイルを探さないので載らない
/// 同じ文の mod が並ぶ                             2 つの mod のテストが 1 つの describe に載る
/// ```
fn descend(items: &[Item], at: &str, dir: &Path) -> Result<Vec<Test>, String> {
    let found = items
        .iter()
        .map(|item| item_tests(item, at, dir))
        .collect::<Result<Vec<_>, String>>()?;
    let mods: Vec<&Both> = found.iter().filter_map(|(m, _)| m.as_ref()).collect();
    let same = Lang::ALL
        .iter()
        .find_map(|&lang| repeated(mods.iter().map(|m| m.get(lang))).first().copied());
    match same {
        Some(same) => Err(format!("同じ文の mod が並んでいる: {at} / {same}")),
        None => Ok(found.into_iter().flat_map(|(_, tests)| tests).collect()),
    }
}

/// 1 つの item のテスト。item がテストを含む `mod` なら、その文も返す。
fn item_tests(item: &Item, at: &str, dir: &Path) -> Result<(Option<Both>, Vec<Test>), String> {
    match item {
        Item::Mod(m) if m.attrs.iter().any(|a| a.path().is_ident("path")) => Err(format!(
            "#[path] の付いた mod は読まない: {at} / {}",
            m.ident
        )),
        Item::Mod(m) => {
            let ident = m.ident.to_string();
            let inside = format!("{at} / {ident}");
            let sub = dir.join(&ident);
            // `mod x;` のファイルの先頭の `#![cfg]` は、`m.attrs` ではなく `file.attrs` にある。
            let (docs, tests, skip) = match &m.content {
                Some((_, inner)) => (
                    doc_lines(&m.attrs, true),
                    descend(inner, &inside, &sub)?,
                    skipped(&m.attrs),
                ),
                None => {
                    let file = mod_file(dir, &ident)?;
                    (
                        doc_lines(&file.attrs, true),
                        descend(&file.items, &inside, &sub)?,
                        skipped(&m.attrs) || skipped(&file.attrs),
                    )
                }
            };
            match (skip, tests.is_empty()) {
                (true, false) => Err(format!("実行されないことがあるテスト: {inside}")),
                (_, true) => Ok((None, tests)),
                (false, false) => {
                    let name = both(&docs, &format!("mod {inside}"))?;
                    named(&ident, &name.en, Kind::RustMod, &format!("mod {inside}"))?;
                    let tests = tests
                        .into_iter()
                        .map(|t| Test {
                            place: name.nest(&t.place),
                            ..t
                        })
                        .collect();
                    Ok((Some(name), tests))
                }
            }
        }
        Item::Macro(m) if m.ident.is_none() => Err(format!(
            "マクロの中のテストは読めない: {at} / {}!",
            m.mac
                .path
                .segments
                .last()
                .map_or(String::new(), |s| s.ident.to_string())
        )),
        Item::Fn(f) if is_test(&f.attrs) && skipped(&f.attrs) => Err(format!(
            "実行されないことがあるテスト: {at} / {}",
            f.sig.ident
        )),
        Item::Fn(f) if is_test(&f.attrs) => {
            let name = f.sig.ident.to_string();
            let here = format!("{at} / {name}");
            let what = both(&doc_lines(&f.attrs, false), &here)?;
            named(&name, &what.en, Kind::RustTest, &here)?;
            Ok((
                None,
                vec![Test {
                    name,
                    what,
                    place: Both::default(),
                    stories: marked(&f.attrs, &here)?,
                }],
            ))
        }
        Item::Fn(f) => match marked(&f.attrs, &format!("{at} / {}", f.sig.ident))?.is_empty() {
            true => Ok((None, Vec::new())),
            false => Err(format!(
                "テストでない関数に #[story] が付いている: {at} / {}",
                f.sig.ident
            )),
        },
        _ => Ok((None, Vec::new())),
    }
}

/// Python の 1 行を左から読んでいるときの状態。
#[derive(Clone, Copy)]
enum Lex {
    Code,
    /// `'` か `"` の文字列。行の中で閉じる。
    Short(char),
    /// 三重引用符の文字列。行をまたいで続く。
    Long(&'static str),
}

/// 1 行を左から読み、行の終わりで開いたままの三重引用符を返す。`open` は、行の始まりで
/// 開いている三重引用符。引用符の中の `#` と三重引用符、`#` のコメントの中の引用符は
/// 文字列の始まりと終わりにしない。三重引用符を閉じた行の残りも読む。
fn string_after(line: &str, open: Option<&'static str>) -> Option<&'static str> {
    let mut lex = open.map_or(Lex::Code, Lex::Long);
    let mut rest = line;
    while let Some(c) = rest.chars().next() {
        let triple = if c == '"' { "\"\"\"" } else { "'''" };
        let (next, used) = match (lex, c) {
            (Lex::Code, '#') => return None,
            (Lex::Code, '"' | '\'') if rest.starts_with(triple) => (Lex::Long(triple), 3),
            (Lex::Code, '"' | '\'') => (Lex::Short(c), 1),
            (Lex::Short(_) | Lex::Long(_), '\\') => {
                (lex, 1 + rest[1..].chars().next().map_or(0, char::len_utf8))
            }
            (Lex::Short(q), c) if c == q => (Lex::Code, 1),
            (Lex::Long(q), _) if rest.starts_with(q) => (Lex::Code, 3),
            _ => (lex, c.len_utf8()),
        };
        lex = next;
        rest = &rest[used..];
    }
    match lex {
        Lex::Long(q) => Some(q),
        Lex::Code | Lex::Short(_) => None,
    }
}

/// Python のブロックの種類。
enum Scope {
    /// ファイルの直下。
    Top,
    /// `def describe_`。中身は describe の文。
    Describe(Both),
    /// `class`。pytest-describe は中の関数を集めない。
    Class,
    /// ほかの `def`。テストの中の `def` を、describe の直下の `def` と区別するために数える。
    Function,
    /// `if`、`for`、`with` などのブロック。この下の describe とテストは、実行されないことがある。
    Block,
}

/// 開いているブロック。`names` は直下の `def` と `class` の名前、`describes` は直下の
/// describe の文。どちらも重複を見つけるために持つ。
struct Frame {
    indent: Option<usize>,
    scope: Scope,
    names: Vec<String>,
    describes: Vec<Both>,
}

impl Frame {
    fn new(indent: Option<usize>, scope: Scope) -> Self {
        Frame {
            indent,
            scope,
            names: Vec::new(),
            describes: Vec::new(),
        }
    }
}

/// docstring を待っている `def`。
enum Waiting {
    Describe {
        name: String,
        indent: usize,
    },
    Test {
        name: String,
        place: Both,
        stories: Vec<String>,
    },
}

impl Waiting {
    fn name(&self) -> &str {
        match self {
            Waiting::Describe { name, .. } | Waiting::Test { name, .. } => name,
        }
    }
}

/// docstring を読んでいるところ。
enum Doc {
    Off,
    /// `def` の行を読んだが、docstring はまだ始まっていない。`bool` は、`def` の行が `:` で
    /// 終わったか。引数を複数行に書くと、`def` の行は `):` の行で終わる。
    Before(Waiting, bool),
    /// docstring の中。読んだ行をためる。
    Inside(Waiting, Vec<String>),
}

struct Scan {
    frames: Vec<Frame>,
    /// 次の `def` に付く `@story` の番号。
    pending: Vec<String>,
    /// 次の `def` に `@pytest.fixture` が付いているか。
    fixture: bool,
    /// 開いている三重引用符。閉じるまで行を読まない。
    string: Option<&'static str>,
    doc: Doc,
    out: Vec<Test>,
}

/// `"""` だけの行か。describe とテストの docstring は、この行で始めてこの行で閉じる。
fn quotes(body: &str) -> bool {
    body.trim_end() == "\"\"\""
}

/// Python のテストファイルを行単位で読む。describe はインデントで入れ子にする。
///
/// 三重引用符の中の行は読まない。セルの中身として書いた `def fib` を関数と見なすと、
/// インデントが 0 なので、開いている describe を閉じてしまう。
///
/// describe の中で `@story` を付けた関数をテストと見なす。pytest-describe は describe の
/// 中の `_` で始まらない関数をすべてテストとして集めるので、名前に接頭辞は要らない。
/// describe の外や `class` の中で `@story` を付けた関数はエラーにする。pytest-describe は
/// これを集めないので、実行されないテストが `SPEC.ja.md` と `SPEC.en.md` に載る。反対に、`@story` の無い
/// テストは `tests/stories.py` が実行する前に失敗させる。
///
/// 同じブロックの直下に同じ名前の `def` が 2 つあるとエラーにする。後の `def` が前の
/// テストや describe を隠すので、pytest は前のものを集めないのに、ここでは載せてしまう。
fn python_tests(text: &str, layer: &str) -> Result<Vec<Test>, String> {
    let start = Scan {
        frames: vec![Frame::new(None, Scope::Top)],
        pending: Vec::new(),
        fixture: false,
        string: None,
        doc: Doc::Off,
        out: Vec::new(),
    };
    let done = text
        .lines()
        .try_fold(start, |scan, line| python_line(scan, line, layer))?;
    match done.doc {
        Doc::Off => Ok(done.out),
        Doc::Before(w, _) => Err(no_doc(layer, &w)),
        Doc::Inside(w, _) => Err(format!(
            "docstring が閉じていない。\"\"\" だけの行で閉じる: {layer} / {}",
            w.name()
        )),
    }
}

/// `def` のすぐ後ろに docstring が無いときのエラー。
fn no_doc(layer: &str, w: &Waiting) -> String {
    format!(
        "def のすぐ後ろに、\"\"\" だけの行で始めて \"\"\" だけの行で閉じる docstring を書く: {layer} / {}",
        w.name()
    )
}

/// `def` の行がこの行で終わるか。行の後ろのコメントは見ない。
fn ends_header(body: &str) -> bool {
    body.split(" #")
        .next()
        .unwrap_or(body)
        .trim_end()
        .ends_with(':')
}

/// ブロックを始める行か。`match` と `case` は名前にも使えるので、`:` で終わる行だけにする。
fn opens_block(body: &str) -> bool {
    let body = body.strip_prefix("async ").unwrap_or(body);
    match body
        .split(|c: char| !(c.is_alphanumeric() || c == '_'))
        .next()
    {
        Some("if" | "elif" | "else" | "for" | "while" | "with" | "try" | "except" | "finally") => {
            true
        }
        Some("match" | "case") => ends_header(body),
        _ => false,
    }
}

/// `del a, b` で消す名前か、`a = ...` か `a: T = ...` で値を入れ直す名前。
fn rebound(body: &str) -> Vec<&str> {
    match body.strip_prefix("del ") {
        Some(rest) => rest.split(',').map(str::trim).collect(),
        None => {
            let end = body
                .find(|c: char| !(c.is_alphanumeric() || c == '_'))
                .unwrap_or(body.len());
            let (name, rest) = body.split_at(end);
            let assigns = (rest.starts_with(" =") && !rest.starts_with(" =="))
                || (rest.starts_with(':') && rest.contains(" = "));
            match !name.is_empty() && assigns {
                true => vec![name],
                false => Vec::new(),
            }
        }
    }
}

/// `@story("J1", "E3")` の番号。番号は二重引用符の文字列で書く。
fn story_ids(body: &str, layer: &str) -> Result<Vec<String>, String> {
    let inside = body
        .strip_prefix("@story(")
        .and_then(|r| r.rsplit_once(')'))
        .map_or("", |(args, _)| args);
    inside
        .split(',')
        .map(str::trim)
        .filter(|a| !a.is_empty())
        .map(|a| {
            a.strip_prefix('"')
                .and_then(|a| a.strip_suffix('"'))
                .map(str::to_string)
                .ok_or_else(|| {
                    format!("@story の番号は \"J1\" のように二重引用符で書く: {layer} / {body}")
                })
        })
        .collect()
}

/// Python の 1 行を読む。
fn python_line(mut scan: Scan, line: &str, layer: &str) -> Result<Scan, String> {
    let body = line.trim_start();
    match std::mem::replace(&mut scan.doc, Doc::Off) {
        Doc::Inside(w, lines) if quotes(body) => return finish(scan, w, &lines, layer),
        Doc::Inside(w, lines) => {
            scan.doc = Doc::Inside(w, lines.into_iter().chain([body.to_string()]).collect());
            return Ok(scan);
        }
        Doc::Before(w, true) if quotes(body) => {
            scan.doc = Doc::Inside(w, Vec::new());
            return Ok(scan);
        }
        // `def` の行と docstring の間には、空行とコメントだけを書ける。
        Doc::Before(w, true) if body.is_empty() || body.starts_with('#') => {
            scan.doc = Doc::Before(w, true);
            return Ok(scan);
        }
        Doc::Before(w, true) => return Err(no_doc(layer, &w)),
        Doc::Before(w, false)
            if ["def ", "async def ", "@", "class "]
                .iter()
                .any(|p| body.starts_with(p)) =>
        {
            return Err(no_doc(layer, &w));
        }
        Doc::Before(w, false) => {
            scan.doc = Doc::Before(w, ends_header(body));
            return Ok(scan);
        }
        Doc::Off => {}
    }
    let inside = scan.string;
    scan.string = string_after(line, inside);
    if inside.is_some() {
        return Ok(scan);
    }
    let indent = line.len() - body.len();
    if body.starts_with("pytestmark") || body.contains("mark.skip") || body.contains("mark.xfail") {
        // pytest が実行しないことがあるのに、SPEC に載る。
        return Err(format!("実行されないことがあるテスト: {layer} / {body}"));
    }
    if body.starts_with('@') && body.contains("story(") && !body.starts_with("@story(") {
        return Err(format!("@story(...) と書く: {layer} / {body}"));
    }
    if body.starts_with("@story") && !body.contains(')') {
        // 次の行のストーリーを読まないので、テストが SPEC に載らないか、ストーリーが減る。
        return Err(format!("@story(...) は 1 行で書く: {layer} / {body}"));
    }
    if body.starts_with("@story(") {
        scan.pending.extend(story_ids(body, layer)?);
        return Ok(scan);
    }
    if let Some(deco) = body.strip_prefix('@') {
        let path = deco.split('(').next().unwrap_or("").trim();
        scan.fixture |= path.rsplit('.').next() == Some("fixture");
        return Ok(scan);
    }
    if opens_block(body) {
        scan.frames
            .retain(|f| f.indent.is_none_or(|at| at < indent));
        scan.frames.push(Frame::new(Some(indent), Scope::Block));
        return Ok(scan);
    }
    let owner = scan
        .frames
        .iter()
        .rev()
        .find(|f| f.indent.is_none_or(|at| at < indent))
        .filter(|f| matches!(f.scope, Scope::Top | Scope::Describe(_)));
    let gone = owner.and_then(|f| {
        rebound(body)
            .into_iter()
            .find(|n| f.names.iter().any(|m| m == n))
    });
    if let Some(name) = gone {
        // 後から消したり入れ直したりした describe とテストを、pytest は集めない。
        return Err(format!(
            "def の名前を消すか、別の値を入れている: {layer} / {name}"
        ));
    }
    let def = body
        .strip_prefix("async ")
        .unwrap_or(body)
        .strip_prefix("def ")
        .and_then(|rest| rest.split('(').next());
    let class = body
        .strip_prefix("class ")
        .and_then(|rest| rest.split(['(', ':']).next());
    let Some(name) = def.or(class).map(str::trim) else {
        return Ok(scan);
    };
    scan.frames
        .retain(|f| f.indent.is_none_or(|at| at < indent));
    let parent = scan.frames.len() - 1;
    if scan.frames[parent].names.iter().any(|n| n == name) {
        return Err(format!("同じ場所に同じ名前の def がある: {layer} / {name}"));
    }
    scan.frames[parent].names.push(name.to_string());
    let stories = std::mem::take(&mut scan.pending);
    let fixture = std::mem::take(&mut scan.fixture);
    if fixture && !stories.is_empty() {
        // pytest-describe は fixture をテストとして集めない。
        return Err(format!("fixture に @story が付いている: {layer} / {name}"));
    }
    let wanted = name.starts_with("describe_") || !stories.is_empty();
    if wanted && matches!(scan.frames[parent].scope, Scope::Block) {
        return Err(format!(
            "if、for、with などの下の describe とテストは、実行されないことがある: {layer} / {name}"
        ));
    }
    if class.is_some() {
        scan.frames.push(Frame::new(Some(indent), Scope::Class));
        return Ok(scan);
    }
    if name.starts_with("describe_") {
        if !stories.is_empty() {
            return Err(format!("describe に @story が付いている: {layer} / {name}"));
        }
        scan.doc = Doc::Before(
            Waiting::Describe {
                name: name.to_string(),
                indent,
            },
            ends_header(body),
        );
        return Ok(scan);
    }
    let names: Option<Vec<&Both>> = scan.frames[1..]
        .iter()
        .map(|f| match &f.scope {
            Scope::Describe(d) => Some(d),
            Scope::Top | Scope::Class | Scope::Function | Scope::Block => None,
        })
        .collect();
    let place = names.filter(|n| !n.is_empty()).map(|n| Both {
        ja: n
            .iter()
            .map(|d| d.ja.as_str())
            .collect::<Vec<_>>()
            .join(" / "),
        en: n
            .iter()
            .map(|d| d.en.as_str())
            .collect::<Vec<_>>()
            .join(" / "),
    });
    scan.frames.push(Frame::new(Some(indent), Scope::Function));
    if stories.is_empty() {
        return Ok(scan);
    }
    let Some(place) = place else {
        return Err(format!(
            "describe の外のテストは pytest-describe が実行しない: {layer} / {name}"
        ));
    };
    scan.doc = Doc::Before(
        Waiting::Test {
            name: name.to_string(),
            place: place.map(|p| format!("{layer} / {p}")),
            stories,
        },
        ends_header(body),
    );
    Ok(scan)
}

/// docstring を閉じたときに、待っていた `def` を describe かテストにする。
fn finish(mut scan: Scan, w: Waiting, lines: &[String], layer: &str) -> Result<Scan, String> {
    let at = format!("{layer} / {}", w.name());
    let what = both(lines, &at)?;
    let kind = match w {
        Waiting::Describe { .. } => Kind::PyDescribe,
        Waiting::Test { .. } => Kind::PyTest,
    };
    named(w.name(), &what.en, kind, &at)?;
    match w {
        Waiting::Describe { indent, .. } => {
            let parent = scan.frames.len() - 1;
            if scan.frames[parent]
                .describes
                .iter()
                .any(|d| d.ja == what.ja || d.en == what.en)
            {
                return Err(format!(
                    "同じ場所に同じ文の describe がある: {layer} / {}",
                    what.ja
                ));
            }
            scan.frames[parent].describes.push(what.clone());
            scan.frames
                .push(Frame::new(Some(indent), Scope::Describe(what)));
        }
        Waiting::Test {
            name,
            place,
            stories,
        } => scan.out.push(Test {
            name,
            what,
            place,
            stories,
        }),
    }
    Ok(scan)
}

/// ディレクトリにある、名前が `prefix` で始まり拡張子が `ext` のファイルを、
/// (層の名前, パス) にして返す。層の名前はファイル名から `prefix` と拡張子を外したもの。
fn layers(dir: &Path, prefix: &str, ext: &str) -> Result<Vec<(String, PathBuf)>, String> {
    Ok(fs::read_dir(dir)
        .map_err(|e| format!("{}: {e}", dir.display()))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == ext))
        .filter_map(|p| {
            let stem = p.file_stem()?.to_string_lossy().into_owned();
            Some((stem.strip_prefix(prefix)?.to_string(), p))
        })
        .collect())
}

/// `dir` の下のファイル。サブディレクトリの中も含める。
fn files_under(dir: &Path) -> Vec<PathBuf> {
    fs::read_dir(dir)
        .into_iter()
        .flatten()
        .filter_map(|e| e.ok().map(|e| e.path()))
        .flat_map(|p| match p.is_dir() {
            true => files_under(&p),
            false => vec![p],
        })
        .collect()
}

/// テストのランナーは実行するのに、このモジュールが読まないファイル。`tests/` の
/// サブディレクトリの `test_*.py` (pytest はサブディレクトリも探す) と、
/// `crates/leani/tests/` のサブディレクトリの `main.rs` (cargo はテストにする)。
fn unread(root: &Path) -> Vec<PathBuf> {
    let subdirs = |dir: PathBuf| -> Vec<PathBuf> {
        fs::read_dir(dir)
            .into_iter()
            .flatten()
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.is_dir())
            .collect()
    };
    let py = subdirs(root.join("tests"))
        .into_iter()
        .flat_map(|d| files_under(&d))
        .filter(|p| {
            p.file_name()
                .and_then(|n| n.to_str())
                .is_some_and(|n| n.starts_with("test_") && n.ends_with(".py"))
        });
    let rs = subdirs(root.join("crates/leani/tests"))
        .into_iter()
        .map(|d| d.join("main.rs"))
        .filter(|p| p.is_file());
    py.chain(rs).collect()
}

/// テストを、層の名前の順、ファイル内で出てくる順に返す。テストのランナーが実行するのに
/// 読まないファイルがあればエラーにする。
pub fn collect(root: &Path) -> Result<Vec<Test>, String> {
    if let Some(path) = unread(root).first() {
        return Err(format!(
            "spec が読まないテストのファイル。tests/ か crates/leani/tests/ の直下に置く: {}",
            path.display()
        ));
    }
    let mut files = layers(&root.join("crates/leani/tests"), "", "rs")?;
    files.extend(layers(&root.join("tests"), "test_", "py")?);
    files.sort();
    files
        .iter()
        .map(|(layer, path)| {
            let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
            if path.extension().is_some_and(|x| x == "py") {
                return python_tests(&text, layer);
            }
            let file = syn::parse_file(&text).map_err(|e| format!("{}: {e}", path.display()))?;
            let dir = path.parent().unwrap_or(Path::new("."));
            rust_file(&file, layer, dir)
        })
        .collect::<Result<Vec<_>, String>>()
        .map(|v| v.into_iter().flatten().collect())
}

/// 2 回以上出てくる値。出てきた順に 1 回ずつ返す。
fn repeated<'a>(items: impl Iterator<Item = &'a str>) -> Vec<&'a str> {
    let all: Vec<&str> = items.collect();
    all.iter()
        .enumerate()
        .filter(|&(i, x)| all[..i].iter().filter(|y| *y == x).count() == 1)
        .map(|(_, x)| *x)
        .collect()
}

/// ストーリー `sid` が group `gid` に入るか。`sid` は `gid` の後ろに数字を続けたもの。
/// 前方一致にすると、group が A と AB のときに AB1 が両方に入る。
fn in_group(sid: &str, gid: &str) -> bool {
    sid.strip_prefix(gid)
        .is_some_and(|n| !n.is_empty() && n.chars().all(|c| c.is_ascii_digit()))
}

/// `stories.toml` の中だけで分かる誤り。ID の重複と、どの group にも入らないストーリー。
/// group に入らないストーリーは `SPEC.ja.md` と `SPEC.en.md` に出てこないので、テストがあっても気づけない。
fn story_complaints(stories: &Stories) -> Vec<String> {
    let dup_story = repeated(stories.story.iter().map(|s| s.id.as_str()))
        .into_iter()
        .map(|id| format!("story の番号が重複している: {id}"));
    let dup_group = repeated(stories.group.iter().map(|g| g.id.as_str()))
        .into_iter()
        .map(|id| format!("group の番号が重複している: {id}"));
    let orphan = stories
        .story
        .iter()
        .filter(|s| !stories.group.iter().any(|g| in_group(&s.id, &g.id)))
        .map(|s| format!("どの group にも入らない: {}", s.id));
    dup_story.chain(dup_group).chain(orphan).collect()
}

/// 生成を止める理由。`#[story]` の付け忘れ、ストーリー番号の書き間違い、
/// `stories.toml` の誤り、同じ場所の同じ文のテスト。
pub fn complaints(stories: &Stories, tests: &[Test]) -> Vec<String> {
    let built = stories
        .unbuilt
        .iter()
        .filter(|sid| tests.iter().any(|t| t.stories.contains(sid)))
        .map(|sid| format!("unbuilt にあるのにテストがある: {sid}"));
    let places: Vec<String> = Lang::ALL
        .iter()
        .flat_map(|&lang| {
            tests
                .iter()
                .map(move |t| format!("{} / {}", t.place.get(lang), t.what.get(lang)))
        })
        .collect();
    let same = repeated(places.iter().map(String::as_str))
        .into_iter()
        .map(|p| format!("同じ文のテストがある: {p}"));
    story_complaints(stories)
        .into_iter()
        .chain(built)
        .chain(same)
        .chain(test_complaints(stories, tests))
        .collect()
}

/// テストごとの誤りと、`unbuilt` の番号の書き間違い。
fn test_complaints(stories: &Stories, tests: &[Test]) -> Vec<String> {
    let per_test = tests.iter().flat_map(|t| {
        let missing = t
            .stories
            .is_empty()
            .then(|| format!("story が無い: {} / {}", t.place.ja, t.what.ja));
        let unknown = t
            .stories
            .iter()
            .filter(|sid| !stories.has(sid))
            .map(|sid| format!("stories.toml に無い番号: {sid} ({})", t.what.ja));
        missing.into_iter().chain(unknown)
    });
    let unbuilt = stories
        .unbuilt
        .iter()
        .filter(|sid| !stories.has(sid))
        .map(|sid| format!("unbuilt にあるのに story に無い: {sid}"));
    per_test.chain(unbuilt).collect()
}

// ------------------------------------------------------------------- 組み立て

fn section(stories: &Stories, tests: &[Test], story: &Story, lang: Lang) -> String {
    let lines: Vec<String> = tests
        .iter()
        .filter(|t| t.stories.contains(&story.id))
        .map(|t| format!("- {} ({})", t.what.get(lang), t.place.get(lang)))
        .collect();
    let body = match (lines.is_empty(), stories.unbuilt.contains(&story.id)) {
        (false, _) => lines.join("\n") + "\n",
        (true, true) => lang.unbuilt().to_string(),
        (true, false) => lang.untested().to_string(),
    };
    format!("### {} {}\n\n{body}", story.id, story.text.get(lang))
}

pub fn render(stories: &Stories, tests: &[Test], lang: Lang) -> Result<String, Vec<String>> {
    let bad = complaints(stories, tests);
    if !bad.is_empty() {
        return Err(bad);
    }
    let head = format!(
        "{}{}",
        lang.head(),
        lang.count(stories.story.len(), tests.len())
    );
    let groups = stories.group.iter().filter_map(|g| {
        let ids: Vec<&Story> = stories
            .story
            .iter()
            .filter(|s| in_group(&s.id, &g.id))
            .collect();
        if ids.is_empty() {
            None
        } else {
            Some(
                std::iter::once(format!("## {}. {}\n", g.id, g.title.get(lang)))
                    .chain(ids.iter().map(|s| section(stories, tests, s, lang)))
                    .collect::<Vec<_>>()
                    .join("\n"),
            )
        }
    });
    Ok(std::iter::once(head)
        .chain(groups)
        .collect::<Vec<_>>()
        .join("\n"))
}

/// `stories.toml` とテストから、`lang` の文で生成した中身。
pub fn generate(root: &Path, lang: Lang) -> Result<String, String> {
    let stories = stories(root)?;
    let tests = collect(root)?;
    render(&stories, &tests, lang).map_err(|bad| bad.join("\n"))
}

/// `lang` の生成結果が `lang.out()` のファイルと同じか確かめる。違えば理由を返す。
pub fn check(root: &Path, lang: Lang) -> Result<(), String> {
    let want = generate(root, lang)?;
    let out = lang.out();
    match fs::read_to_string(root.join(out)) {
        Ok(have) if have == want => Ok(()),
        _ => Err(format!("{out} が古い: cargo run -p spec")),
    }
}

