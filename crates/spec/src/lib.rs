/// 文の言語。言語ごとに 1 つのファイルを生成する。
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Ja,
    En,
}

impl Lang {
    pub const ALL: [Lang; 2] = [Lang::Ja, Lang::En];

    /// 生成するファイル。
    pub fn out(self) -> &'static str {
        match self {
            Lang::Ja => "SPEC.ja.md",
            Lang::En => "SPEC.en.md",
        }
    }

    /// ファイルの先頭。相手の言語のファイルへのリンクは、このファイルを読めない人が
    /// 見つけられるように、相手の言語で書く。
    fn head(self) -> &'static str {
        match self {
            Lang::Ja => {
                "<!-- crates/spec が crates/leani/tests/ と tests/ から生成する。手で編集しない。 -->

# leani の性質一覧

English version: [SPEC.en.md](SPEC.en.md)

leani が誰の何を助けるか (`stories.toml`) に、それを確かめているテストの
文を並べたもの。テストはすべて `cargo nextest run` (層 kernel は `uv run pytest`)
で実際に確かめられている。
項目が増えたり減ったりするのは、ストーリーかテストを追加または削除したときだけ。

    cargo run -p spec

"
            }
            Lang::En => {
                "<!-- Generated by crates/spec from crates/leani/tests/ and tests/. Do not edit by hand. -->

# Properties of leani

日本語版: [SPEC.ja.md](SPEC.ja.md)

Each user story in `stories.toml` (who leani helps, and how), followed by the tests
that check it. Every test runs in `cargo nextest run` (`uv run pytest` for the kernel
layer). The number of items changes only when a story or a test is added or removed.

    cargo run -p spec

"
            }
        }
    }

    /// ストーリーとテストの件数の行。
    fn count(self, stories: usize, tests: usize) -> String {
        match self {
            Lang::Ja => format!(
                "ストーリー {stories} 件、テスト {tests} 件。括弧の中はテストの場所\n(層 / describe)。\n"
            ),
            Lang::En => format!(
                "{stories} stories, {tests} tests. In parentheses: where the test is\n(layer / describe).\n"
            ),
        }
    }

    /// `unbuilt` にあるストーリーの本文。
    fn unbuilt(self) -> &'static str {
        match self {
            Lang::Ja => "まだ作っていない。\n",
            Lang::En => "Not built yet.\n",
        }
    }

    /// テストが 0 件のストーリーの本文。
    fn untested(self) -> &'static str {
        match self {
            Lang::Ja => "**確かめているテストが無い。**\n",
            Lang::En => "**No test checks this.**\n",
        }
    }
}

/// 日本語と英語の文の組。
#[derive(Clone, Debug, Default, PartialEq, Eq, Deserialize)]
pub struct Both {
    pub ja: String,
    pub en: String,
}

impl Both {
    pub fn get(&self, lang: Lang) -> &str {
        match lang {
            Lang::Ja => &self.ja,
            Lang::En => &self.en,
        }
    }

    /// 言語ごとに `f` で作った文。
    fn map(&self, f: impl Fn(&str) -> String) -> Both {
        Both {
            ja: f(&self.ja),
            en: f(&self.en),
        }
    }

    /// 外側の文と内側の文を、言語ごとに ` / ` でつなぐ。
    fn nest(&self, inner: &Both) -> Both {
        Both {
            ja: nest(&self.ja, &inner.ja),
            en: nest(&self.en, &inner.en),
        }
    }
}

